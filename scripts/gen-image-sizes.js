// Writes src/Assets/imageSizes.js: intrinsic width/height for every imported asset image,
// keyed by the imported URL, so <Img> can reserve space and avoid layout shift.
// Re-run after adding or changing images (macOS: uses sips): node scripts/gen-image-sizes.js
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const SRC = path.join(__dirname, "..", "src");
const files = new Set();
(function walk(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p);
    else if (/\.(jsx?|tsx?)$/.test(f.name) && f.name !== "imageSizes.js") {
      const re = /from\s+['"]([^'"]*Assets\/[^'"]+\.(?:jpe?g|png|webp))['"]/gi;
      for (const m of fs.readFileSync(p, "utf8").matchAll(re)) files.add(path.resolve(path.dirname(p), m[1]));
    }
  }
})(SRC);

const assets = path.join(SRC, "Assets");
const lines = [];
const entries = [];
[...files].sort().forEach((abs, i) => {
  if (!fs.existsSync(abs)) return;
  const out = execFileSync("sips", ["-g", "pixelWidth", "-g", "pixelHeight", abs]).toString();
  const w = out.match(/pixelWidth: (\d+)/)[1];
  const h = out.match(/pixelHeight: (\d+)/)[1];
  lines.push(`import i${i} from "./${path.relative(assets, abs).split(path.sep).join("/")}";`);
  entries.push(`  [i${i}]: [${w}, ${h}],`);
});

fs.writeFileSync(
  path.join(assets, "imageSizes.js"),
  `// Generated by scripts/gen-image-sizes.js. Do not edit.\n${lines.join("\n")}\n\nconst sizes = {\n${entries.join("\n")}\n};\n\nexport default sizes;\n`
);
console.log(`${entries.length} images`);
